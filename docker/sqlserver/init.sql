IF DB_ID(N'$(DB_NAME)') IS NULL
    CREATE DATABASE [$(DB_NAME)];
GO

IF SUSER_ID(N'$(DB_USER)') IS NULL
    CREATE LOGIN [$(DB_USER)] WITH PASSWORD = N'$(DB_PASSWORD)';
GO

USE [$(DB_NAME)];
GO

IF USER_ID(N'$(DB_USER)') IS NULL
    CREATE USER [$(DB_USER)] FOR LOGIN [$(DB_USER)];
GO

ALTER ROLE db_owner ADD MEMBER [$(DB_USER)];
GO

USE [master];
GO

IF SUSER_ID(N'$(DB_TEST_USER)') IS NULL
    CREATE LOGIN [$(DB_TEST_USER)] WITH PASSWORD = N'$(DB_TEST_PASSWORD)';
GO

ALTER SERVER ROLE dbcreator ADD MEMBER [$(DB_TEST_USER)];
GO
