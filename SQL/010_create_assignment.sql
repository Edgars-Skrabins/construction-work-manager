CREATE TABLE ASSIGNMENT (
    ID INT IDENTITY(1, 1) NOT NULL,
    EMPLOYEE_ID INT NOT NULL,
    WORK_ITEM_ID INT NOT NULL,
    CONSTRUCTION_SITE_ID INT NOT NULL,
    START_DATE DATE NOT NULL,
    END_DATE DATE NOT NULL,
    STATUS NVARCHAR(20) NOT NULL CONSTRAINT DF_ASSIGNMENT_STATUS DEFAULT N'active',
    CREATED_BY_ID INT NOT NULL,
    CREATED_AT DATETIME2(0) NOT NULL CONSTRAINT DF_ASSIGNMENT_CREATED_AT DEFAULT SYSUTCDATETIME(),
    UPDATED_AT DATETIME2(0) NOT NULL CONSTRAINT DF_ASSIGNMENT_UPDATED_AT DEFAULT SYSUTCDATETIME(),
    CONSTRAINT PK_ASSIGNMENT PRIMARY KEY (ID),
    CONSTRAINT FK_ASSIGNMENT_EMPLOYEE_ID FOREIGN KEY (EMPLOYEE_ID) REFERENCES EMPLOYEE (ID),
    CONSTRAINT FK_ASSIGNMENT_WORK_ITEM_ID FOREIGN KEY (WORK_ITEM_ID) REFERENCES WORK_ITEM (ID),
    CONSTRAINT FK_ASSIGNMENT_CONSTRUCTION_SITE_ID FOREIGN KEY (CONSTRUCTION_SITE_ID) REFERENCES CONSTRUCTION_SITE (ID),
    CONSTRAINT FK_ASSIGNMENT_CREATED_BY_ID FOREIGN KEY (CREATED_BY_ID) REFERENCES EMPLOYEE (ID),
    CONSTRAINT CK_ASSIGNMENT_PERIOD CHECK (END_DATE >= START_DATE),
    CONSTRAINT CK_ASSIGNMENT_STATUS CHECK (STATUS IN (N'active', N'done', N'cancelled'))
);
GO

CREATE INDEX IX_ASSIGNMENT_EMPLOYEE_ID ON ASSIGNMENT (EMPLOYEE_ID, START_DATE);
GO

CREATE INDEX IX_ASSIGNMENT_WORK_ITEM_ID ON ASSIGNMENT (WORK_ITEM_ID);
GO

CREATE INDEX IX_ASSIGNMENT_SITE_PERIOD ON ASSIGNMENT (CONSTRUCTION_SITE_ID, START_DATE, END_DATE) INCLUDE (STATUS, EMPLOYEE_ID);
GO

CREATE INDEX IX_ASSIGNMENT_CREATED_BY_ID ON ASSIGNMENT (CREATED_BY_ID);
GO
