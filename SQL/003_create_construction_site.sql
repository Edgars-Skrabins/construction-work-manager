CREATE TABLE CONSTRUCTION_SITE (
    ID INT IDENTITY(1, 1) NOT NULL,
    NAME NVARCHAR(150) NOT NULL,
    STREET NVARCHAR(200) NOT NULL,
    CITY NVARCHAR(100) NOT NULL,
    COUNTRY NVARCHAR(100) NOT NULL,
    AREA_M2 DECIMAL(10, 2) NOT NULL,
    REQUIRED_ACCESS_LEVEL_ID TINYINT NOT NULL,
    CREATED_AT DATETIME2(0) NOT NULL CONSTRAINT DF_CONSTRUCTION_SITE_CREATED_AT DEFAULT SYSUTCDATETIME(),
    UPDATED_AT DATETIME2(0) NOT NULL CONSTRAINT DF_CONSTRUCTION_SITE_UPDATED_AT DEFAULT SYSUTCDATETIME(),
    CONSTRAINT PK_CONSTRUCTION_SITE PRIMARY KEY (ID),
    CONSTRAINT UQ_CONSTRUCTION_SITE_NAME UNIQUE (NAME),
    CONSTRAINT FK_CONSTRUCTION_SITE_REQUIRED_ACCESS_LEVEL_ID FOREIGN KEY (REQUIRED_ACCESS_LEVEL_ID) REFERENCES ACCESS_LEVEL (ID),
    CONSTRAINT CK_CONSTRUCTION_SITE_AREA_M2 CHECK (AREA_M2 > 0)
);
GO

CREATE INDEX IX_CONSTRUCTION_SITE_REQUIRED_ACCESS_LEVEL_ID ON CONSTRUCTION_SITE (REQUIRED_ACCESS_LEVEL_ID);
GO
