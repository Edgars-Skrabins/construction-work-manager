CREATE TABLE WORK_ITEM (
    ID INT IDENTITY(1, 1) NOT NULL,
    NAME NVARCHAR(150) NOT NULL,
    DESCRIPTION NVARCHAR(1000) NULL,
    CREATED_AT DATETIME2(0) NOT NULL CONSTRAINT DF_WORK_ITEM_CREATED_AT DEFAULT SYSUTCDATETIME(),
    UPDATED_AT DATETIME2(0) NOT NULL CONSTRAINT DF_WORK_ITEM_UPDATED_AT DEFAULT SYSUTCDATETIME(),
    CONSTRAINT PK_WORK_ITEM PRIMARY KEY (ID),
    CONSTRAINT UQ_WORK_ITEM_NAME UNIQUE (NAME)
);
GO
