CREATE TABLE ACCESS_LEVEL (
    ID TINYINT NOT NULL,
    NAME NVARCHAR(50) NOT NULL,
    CONSTRAINT PK_ACCESS_LEVEL PRIMARY KEY (ID),
    CONSTRAINT UQ_ACCESS_LEVEL_NAME UNIQUE (NAME),
    CONSTRAINT CK_ACCESS_LEVEL_ID CHECK (ID BETWEEN 1 AND 4)
);
GO

INSERT INTO ACCESS_LEVEL (ID, NAME) VALUES
    (1, N'General'),
    (2, N'Restricted'),
    (3, N'Critical infrastructure'),
    (4, N'Classified');
GO
