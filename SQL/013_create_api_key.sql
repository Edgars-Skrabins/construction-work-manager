CREATE TABLE API_KEY (
    ID INT IDENTITY(1, 1) NOT NULL,
    KEY_ID NVARCHAR(8) NOT NULL,
    CLIENT_NAME NVARCHAR(100) NOT NULL,
    SECRET_HASH NVARCHAR(64) NOT NULL,
    EXPIRES_AT DATETIME2(0) NULL,
    LAST_USED_AT DATETIME2(0) NULL,
    REVOKED_AT DATETIME2(0) NULL,
    CREATED_AT DATETIME2(0) NOT NULL CONSTRAINT DF_API_KEY_CREATED_AT DEFAULT SYSUTCDATETIME(),
    UPDATED_AT DATETIME2(0) NOT NULL CONSTRAINT DF_API_KEY_UPDATED_AT DEFAULT SYSUTCDATETIME(),
    CONSTRAINT PK_API_KEY PRIMARY KEY (ID),
    CONSTRAINT UQ_API_KEY_KEY_ID UNIQUE (KEY_ID),
    CONSTRAINT CK_API_KEY_KEY_ID CHECK (LEN(KEY_ID) = 8 AND KEY_ID NOT LIKE N'%[^0-9a-f]%' COLLATE Latin1_General_100_BIN2),
    CONSTRAINT CK_API_KEY_CLIENT_NAME CHECK (LEN(LTRIM(RTRIM(CLIENT_NAME))) > 0),
    CONSTRAINT CK_API_KEY_SECRET_HASH CHECK (LEN(SECRET_HASH) = 64 AND SECRET_HASH NOT LIKE N'%[^0-9a-f]%' COLLATE Latin1_General_100_BIN2)
);
GO
