CREATE TABLE EMPLOYEE (
    ID INT IDENTITY(1, 1) NOT NULL,
    FIRST_NAME NVARCHAR(100) NOT NULL,
    LAST_NAME NVARCHAR(100) NOT NULL,
    BIRTH_DATE DATE NOT NULL,
    ACCESS_LEVEL_ID TINYINT NOT NULL,
    ROLE NVARCHAR(20) NOT NULL,
    MANAGER_ID INT NULL,
    CREATED_AT DATETIME2(0) NOT NULL CONSTRAINT DF_EMPLOYEE_CREATED_AT DEFAULT SYSUTCDATETIME(),
    UPDATED_AT DATETIME2(0) NOT NULL CONSTRAINT DF_EMPLOYEE_UPDATED_AT DEFAULT SYSUTCDATETIME(),
    CONSTRAINT PK_EMPLOYEE PRIMARY KEY (ID),
    CONSTRAINT FK_EMPLOYEE_ACCESS_LEVEL_ID FOREIGN KEY (ACCESS_LEVEL_ID) REFERENCES ACCESS_LEVEL (ID),
    CONSTRAINT FK_EMPLOYEE_MANAGER_ID FOREIGN KEY (MANAGER_ID) REFERENCES EMPLOYEE (ID),
    CONSTRAINT CK_EMPLOYEE_ROLE CHECK (ROLE IN (N'admin', N'manager', N'employee')),
    CONSTRAINT CK_EMPLOYEE_NOT_OWN_MANAGER CHECK (MANAGER_ID <> ID)
);
GO

CREATE INDEX IX_EMPLOYEE_ACCESS_LEVEL_ID ON EMPLOYEE (ACCESS_LEVEL_ID);
GO

CREATE INDEX IX_EMPLOYEE_MANAGER_ID ON EMPLOYEE (MANAGER_ID);
GO
