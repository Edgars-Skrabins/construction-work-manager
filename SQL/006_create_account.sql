CREATE TABLE ACCOUNT (
    EMPLOYEE_ID INT NOT NULL,
    EMAIL NVARCHAR(254) NOT NULL,
    PASSWORD_HASH NVARCHAR(255) NULL,
    IS_ACTIVE BIT NOT NULL CONSTRAINT DF_ACCOUNT_IS_ACTIVE DEFAULT 1,
    CREATED_AT DATETIME2(0) NOT NULL CONSTRAINT DF_ACCOUNT_CREATED_AT DEFAULT SYSUTCDATETIME(),
    UPDATED_AT DATETIME2(0) NOT NULL CONSTRAINT DF_ACCOUNT_UPDATED_AT DEFAULT SYSUTCDATETIME(),
    CONSTRAINT PK_ACCOUNT PRIMARY KEY (EMPLOYEE_ID),
    CONSTRAINT FK_ACCOUNT_EMPLOYEE_ID FOREIGN KEY (EMPLOYEE_ID) REFERENCES EMPLOYEE (ID),
    CONSTRAINT UQ_ACCOUNT_EMAIL UNIQUE (EMAIL),
    CONSTRAINT CK_ACCOUNT_EMAIL_NORMALIZED CHECK (EMAIL = LOWER(EMAIL) COLLATE Latin1_General_100_CS_AS AND DATALENGTH(EMAIL) = DATALENGTH(LTRIM(RTRIM(EMAIL))))
);
GO
